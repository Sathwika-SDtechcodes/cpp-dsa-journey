#include<iostream>
using namespace std;
/*Demonstrate relational operators*/
int main()
{
  int a = 50,b =30;
  cout << (a==b) << "a and b are equal" << endl;
  cout << (a<=b) << "a is less than or equal to b"<< endl;
  cout << (a>=b) << "a is greater than or equal to b"<< endl;
  cout << (a!=b) << "a is not equal to b" << endl;
  cout << (a>b) << "a is greater than b" << endl;
  cout << (a<b) << "a is less than b" << endl;
  return 0;
}
